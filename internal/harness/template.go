package harness

const witnessHeader = `// Code generated by go-flake-hunter; DO NOT EDIT.
// Temporary witness file — deleted after the run.

`

// witnessTemplate renders the temporary witness file.
//
// The package clause must match the tests being called: a test in
// `package foo_test` cannot call a test in `package foo` (undefined at
// compile time), which is why the caller passes the resolved clause.
const witnessTemplate = witnessHeader + `package {{.Clause}}

import "testing"

func {{.Func}}(t *testing.T) {
{{- range .Steps}}
	t.Run({{quote .Label}}, {{.Func}})
{{- end}}
}
`

// parallelTemplate is the witness for concurrency-class flakes.
//
// A sequential witness cannot express this bug: the fixture fails only when two
// different tests are inside the barrier at the same time. Each step therefore
// registers as a parallel subtest, which is the only way to ask `go test` to
// overlap them — and the run must pass -parallel >= len(steps) or Go serialises
// them and the witness silently proves nothing.
const parallelTemplate = witnessHeader + `package {{.Clause}}

import "testing"

func {{.Func}}(t *testing.T) {
{{- range .Steps}}
	t.Run({{quote .Label}}, func(t *testing.T) {
{{- if .WrapParallel}}
		t.Parallel()
{{- end}}
		{{.Func}}(t)
	})
{{- end}}
}
`
